import { chromium } from "@playwright/test";
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const p = await b.newPage({ viewport: { width: 1440, height: 1100 }, colorScheme: "dark" });
await p.goto(`http://127.0.0.1:3031/?w=operate&p=pl_0000`);
await p.waitForTimeout(2000);
await p.getByRole("button", { name: "Add destination" }).first().click();
await p.waitForTimeout(800);
const form = p.getByRole("region", { name: /destination/i }).last();
const box = await p.locator("form").last().boundingBox();
await p.screenshot({ path: process.argv[2], clip: { x: Math.max(0, box.x - 20), y: Math.max(0, box.y - 60), width: Math.min(1440, box.width + 40), height: Math.min(1100, box.height + 100) } });
await b.close();
